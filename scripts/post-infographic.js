import 'dotenv/config';

const webhookUrl = process.env.DISCORD_WEBHOOK_URL;
if (!webhookUrl) {
  console.error('No DISCORD_WEBHOOK_URL found in environment.');
  process.exit(1);
}

const payload = {
  embeds: [
    {
      title: '🏛️ DAEDALUS: The Architect of Autonomous Coding',
      description: 'Check out this epic system architecture infographic generated by NotebookLM! It visualizes the complete **Loop Engineering Lifecycle**, **Multi-Agent Roles**, **Autonomous Finn Loop**, and **Embedded Model Router**.',
      color: 0x7c3aed, // Purple accent
      image: {
        url: 'https://raw.githubusercontent.com/bgill55/daedalus/main/docs/images/notebooklm_infographic.jpg',
      },
      fields: [
        {
          name: '🔄 Loop Engineering',
          value: 'Surgical Coder → Stack Verification → Debugger Repair Loop → Clean State Rollback',
          inline: false,
        },
        {
          name: '🚀 Autonomous Finn Loop',
          value: '`/spec` Requirements → Daemon `--loop` → GitHub PR → Discord Notification',
          inline: false,
        },
      ],
      footer: {
        text: 'Daedalus AI Agent Infrastructure • Generated with NotebookLM',
      },
    },
  ],
};

async function post() {
  try {
    const res = await fetch(webhookUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload),
    });

    if (!res.ok) {
      const errText = await res.text();
      console.error('❌ Failed to post to Discord:', res.status, errText);
      process.exit(1);
    }

    console.log('✅ Infographic successfully posted to Discord!');
  } catch (err) {
    console.error('❌ Error posting to Discord:', err);
    process.exit(1);
  }
}

post();

